def test_scenario_15_and_16_history_and_actual_energy_independence(client, db):
    """
    Scenarios 15-16:
    15. Verify prediction history and dashboard statistics remain correct.
    16. Verify actual energy recording does not overwrite prediction history.
    """
    # Create batch
    batch_res = client.post("/api/production-batches", json={
        "batchNumber": "BATCH-INDEP-TEST-01",
        "productId": 1,
        "quantity": 150,
        "machineHours": 10.0,
        "machineTypeId": 1,
        "shiftId": 1,
        "productionDate": "2025-06-20",
    })
    assert batch_res.status_code == 201
    batch_id = batch_res.json()["id"]

    # Workflow B: Predict for batch
    pred_res = client.post(f"/api/production-batches/{batch_id}/predict")
    assert pred_res.status_code == 200
    original_estimated = pred_res.json()["estimatedEnergy"]
    pred_id = pred_res.json()["predictionId"]

    # Verify prediction history shows estimated energy and pending actual energy
    hist_res = client.get(f"/api/predictions/{pred_id}")
    assert hist_res.status_code == 200
    hist_item = hist_res.json()
    assert hist_item["estimatedEnergyKwh"] == original_estimated
    assert hist_item["actualEnergyKwh"] is None

    # Scenario 16: Enter actual energy consumed after production run
    update_res = client.put(f"/api/production-batches/{batch_id}", json={
        "actualEnergyConsumedKwh": 512.75,
    })
    assert update_res.status_code == 200
    assert update_res.json()["actualEnergyConsumedKwh"] == 512.75

    # Confirm original prediction record was NOT overwritten or destroyed
    hist_res_after = client.get(f"/api/predictions/{pred_id}")
    assert hist_res_after.status_code == 200
    hist_item_after = hist_res_after.json()
    assert hist_item_after["estimatedEnergyKwh"] == original_estimated
    assert hist_item_after["actualEnergyKwh"] == 512.75

    # Check dashboard stats reflect updated actuals
    dash_res = client.get("/api/dashboard/stats")
    assert dash_res.status_code == 200
    dash_data = dash_res.json()
    assert dash_data["totalPredictions"] >= 1
    assert dash_data["completedBatches"] >= 1


def test_scenario_17_retraining_failure_preserves_previous_valid_model(tmp_path):
    """
    Scenario 17:
    Verify that model retraining failure does not replace or corrupt the previous valid model.
    """
    model_path = tmp_path / "model.joblib"
    metrics_path = tmp_path / "metrics.json"

    # 1. Train an initial valid model
    from backend.ml.dataset import generate_synthetic_dataset
    csv_valid = generate_synthetic_dataset(output_path=tmp_path / "valid.csv", num_samples=100)
    initial_metrics = train_and_evaluate(
        data_path=csv_valid,
        model_save_path=model_path,
        metrics_save_path=metrics_path,
    )
    assert model_path.exists()
    initial_mtime = model_path.stat().st_mtime_ns

    # 2. Attempt training with invalid / corrupt dataset (e.g. all 0s or empty target)
    invalid_csv = tmp_path / "invalid.csv"
    with open(invalid_csv, "w", encoding="utf-8") as f:
        f.write("quantity,machine_hours,machine_type,shift,actual_energy_consumed_kwh\n")
        # only 5 rows with invalid values (below min 50 rows)
        f.write("10,2,CNC,Morning,0\n")

    with pytest.raises(Exception):
        train_and_evaluate(
            data_path=invalid_csv,
            model_save_path=model_path,
            metrics_save_path=metrics_path,
        )

    # 3. Verify original model artifact remains intact and unchanged
    assert model_path.exists()
    assert model_path.stat().st_mtime_ns == initial_mtime

    with open(metrics_path, "r", encoding="utf-8") as f:
        surviving_metrics = json.load(f)
    assert surviving_metrics["model_version"] == initial_metrics["model_version"]
