def test_scenario_1_to_7_dynamic_machine_creation_and_untrained_rejection(client, db):
    """
    Scenarios 1-7:
    1. Create new machine type named 'GEARBOX'.
    2. Confirm it exists in SQLite database.
    3. Confirm API client / frontend can retrieve it.
    4. Confirm production batch form can select it and create batch.
    5. Confirm prediction form can select it.
    6. Attempt prediction before model has been trained for GEARBOX.
    7. Verify application handles this correctly with HTTP 422 and actionable message.
    """
    # Ensure predictor is using base model without GEARBOX initially
    original_machines = [m for m in predictor.get_supported_machine_types() if m != "GEARBOX"]
    if "GEARBOX" in predictor.get_supported_machine_types():
        # Temporarily test with a unique dynamic machine type to verify untrained rejection
        new_machine_name = "TURBINE_PRESS"
    else:
        new_machine_name = "GEARBOX"

    # Scenario 1: Create machine type
    res = client.post("/api/machine-types", json={"name": new_machine_name, "description": "High torque gearbox assembly"})
    assert res.status_code == 201
    created = res.json()
    assert created["name"] == new_machine_name
    machine_id = created["id"]

    # Scenario 2: Confirm it exists in SQLite database
    db_machine = db.query(MachineType).filter(MachineType.name == new_machine_name).first()
    assert db_machine is not None
    assert db_machine.id == machine_id

    # Scenario 3: Confirm frontend can retrieve it
    list_res = client.get("/api/machine-types")
    assert list_res.status_code == 200
    names = [m["name"] for m in list_res.json()]
    assert new_machine_name in names

    # Scenario 4: Confirm production batch form can select it
    batch_res = client.post("/api/production-batches", json={
        "batchNumber": f"BATCH-TEST-{new_machine_name}-01",
        "productId": 1,
        "quantity": 120,
        "machineHours": 6.5,
        "machineTypeId": machine_id,
        "shiftId": 1,
        "productionDate": "2025-06-15",
    })
    assert batch_res.status_code == 201
    batch_data = batch_res.json()
    assert batch_data["machineTypeId"] == machine_id
    assert batch_data["machineType"]["name"] == new_machine_name
    batch_id = batch_data["id"]

    # Scenario 5 & 6 & 7: Attempt prediction before model is trained for this category
    # Direct endpoint
    pred_res = client.post("/predict-energy", json={
        "quantity": 120,
        "machineHours": 6.5,
        "machineType": new_machine_name,
        "shift": "Morning",
    })
    assert pred_res.status_code == 422
    err_detail = pred_res.json()["detail"]
    assert "registered in the database" in err_detail
    assert "not been trained for this category" in err_detail
    assert "retrain" in err_detail.lower()

    # Batch prediction endpoint (Workflow B)
    batch_pred_res = client.post(f"/api/production-batches/{batch_id}/predict")
    assert batch_pred_res.status_code == 422
    assert "not been trained for this category" in batch_pred_res.json()["detail"]


def test_scenario_8_to_12_synthetic_data_retraining_and_gearbox_prediction(client, db):
    """
    Scenarios 8-12:
    8. Add appropriate training records / clearly labeled synthetic records for GEARBOX.
    9. Retrain model using the training pipeline.
    10. Confirm retrained model can predict for GEARBOX.
    11. Verify output is finite, numeric, and non-negative.
    12. Confirm predictions are generated by the trained model, not hardcoded.
    """
    # Ensure GEARBOX is in database
    if not db.query(MachineType).filter(MachineType.name == "GEARBOX").first():
        client.post("/api/machine-types", json={"name": "GEARBOX", "description": "Gearbox assembly"})

    # Scenario 8 & 9: Retrain model with CNC, Lathe, Milling Machine, and GEARBOX
    all_machines = ["CNC", "Lathe", "Milling Machine", "GEARBOX"]
    metrics = retrain_with_machine_types(machine_types=all_machines, num_samples=1200, seed=42)
    assert metrics is not None
    assert "GEARBOX" in metrics["known_categories"]["machine_types"]
    assert metrics["metrics"]["r2_score"] >= 0.70

    # Ensure predictor reloaded
    predictor.reload()
    assert predictor.is_machine_type_supported("GEARBOX")

    # Scenario 10: Confirm retrained model can predict for GEARBOX
    res1 = client.post("/predict-energy", json={
        "quantity": 100,
        "machineHours": 8.0,
        "machineType": "GEARBOX",
        "shift": "Morning",
    })
    assert res1.status_code == 200
    data1 = res1.json()

    # Scenario 11: Output is finite, numeric, and positive
    est1 = data1["estimatedEnergy"]
    assert isinstance(est1, (int, float))
    assert est1 > 0
    assert not (est1 != est1)  # not NaN

    # Scenario 12: Confirm predictions are generated by model (not a hardcoded value)
    res2 = client.post("/predict-energy", json={
        "quantity": 250,
        "machineHours": 14.0,
        "machineType": "GEARBOX",
        "shift": "Morning",
    })
    assert res2.status_code == 200
    est2 = res2.json()["estimatedEnergy"]
    assert est2 > est1, "Higher quantity and machine hours must produce higher energy in regression model"


